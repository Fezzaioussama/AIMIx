"""Value objects shared by the artifact renderers (§7 DTO)."""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

#: The bytes of a picture a document shows, by the path its Markdown gives
#: (``![alt](images/chart.png)``); None when there is no such picture to show.
PictureLoader = Callable[[str], bytes | None]


@dataclass(frozen=True)
class RenderOptions:
    """How documents look; every value comes from settings (§6)."""

    #: TrueType fonts for PDFs. A missing file falls back to a built-in font
    #: that covers Western European text only.
    pdf_font: Path
    pdf_bold_font: Path
    #: Where a document's pictures come from (the user's workspace); None shows
    #: every picture as its alt text.
    pictures: PictureLoader | None = field(default=None, compare=False, repr=False)


#: The agent's text in, the file's bytes out.
Renderer = Callable[[str, RenderOptions], bytes]

#: Written into the metadata of every document an agent saves, so a program that
#: reads the file can tell it was made by AI (EU AI Act, art. 50(2)).
AI_GENERATED_NOTE = "Generated by an AI agent in AIMIx."
AI_GENERATED_KEYWORD = "AI-generated"
